export const translations: Record<Language, typeof en> = { en, hi, mr };

export type TranslationKey = keyof typeof en;

export function translate(lang: Language, key: TranslationKey, vars?: Record<string, string | number>): string {
  let text: string = translations[lang]?.[key] ?? translations.en[key] ?? String(key);
  if (vars) {
    Object.entries(vars).forEach(([k, v]) => {
      text = text.split(`{${k}}`).join(String(v));
    });
  }
  return text;
}
